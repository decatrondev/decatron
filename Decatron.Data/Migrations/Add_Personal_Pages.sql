-- Página personal del streamer (decatron.net/@handle), subfase 5.1. Plan: .dev/plans/pagina-personal/PLAN.md §9.
-- Idempotente. Sin tenant_id por ahora (solo decatron.net); para el SaaS se agrega con RLS y el único pasa a (tenant_id, handle).
BEGIN;

CREATE TABLE IF NOT EXISTS personal_pages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    handle varchar(25) NOT NULL CHECK (handle ~ '^[a-z0-9][a-z0-9_-]{1,23}[a-z0-9]$'),
    handle_changed_at timestamptz,
    draft jsonb NOT NULL DEFAULT '{}'::jsonb,
    published jsonb,
    published_at timestamptz,
    status varchar(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','hidden')),
    hidden_reason varchar(500) NOT NULL DEFAULT '',
    needs_new_handle boolean NOT NULL DEFAULT false,
    revision bigint NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_personal_pages_channel UNIQUE (channel_user_id),
    CONSTRAINT uq_personal_pages_handle UNIQUE (handle)
);

CREATE TABLE IF NOT EXISTS personal_page_handle_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id bigint NOT NULL REFERENCES personal_pages(id) ON DELETE CASCADE,
    handle varchar(25) NOT NULL,
    valid_until timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_personal_page_history_handle ON personal_page_handle_history(handle, valid_until);
CREATE INDEX IF NOT EXISTS ix_personal_page_history_page ON personal_page_handle_history(page_id);

CREATE TABLE IF NOT EXISTS personal_page_reserved_handles (
    handle varchar(25) PRIMARY KEY,
    note varchar(300) NOT NULL DEFAULT '',
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS personal_page_handle_appeals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle varchar(25) NOT NULL,
    requester_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requester_channel_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message varchar(1000) NOT NULL,
    status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','rejected','transferred','withdrawn')),
    review_note varchar(1000) NOT NULL DEFAULT '',
    reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_personal_page_appeals_review ON personal_page_handle_appeals(status, created_at, id);
-- Una sola apelación pendiente por canal y nombre
CREATE UNIQUE INDEX IF NOT EXISTS uq_personal_page_appeals_pending
    ON personal_page_handle_appeals(requester_channel_user_id, handle) WHERE status = 'pending';

GRANT SELECT, INSERT, UPDATE, DELETE ON personal_pages, personal_page_handle_history, personal_page_reserved_handles, personal_page_handle_appeals TO decatron_user;
GRANT USAGE, SELECT ON SEQUENCE personal_pages_id_seq, personal_page_handle_history_id_seq, personal_page_handle_appeals_id_seq TO decatron_user;
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'decatron_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON personal_pages, personal_page_handle_history, personal_page_reserved_handles, personal_page_handle_appeals TO decatron_app;
        GRANT USAGE, SELECT ON SEQUENCE personal_pages_id_seq, personal_page_handle_history_id_seq, personal_page_handle_appeals_id_seq TO decatron_app;
    END IF;
END $$;

COMMIT;
