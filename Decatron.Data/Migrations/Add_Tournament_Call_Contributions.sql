BEGIN;
ALTER TABLE tournament_call_page ADD COLUMN IF NOT EXISTS donations_open boolean NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS tournament_call_contributions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reference varchar(150) NOT NULL UNIQUE,
 payment_id integer UNIQUE REFERENCES supporter_payments(id) ON DELETE RESTRICT,
 payment_reference varchar(300) NOT NULL DEFAULT '',
 application_id bigint REFERENCES tournament_call_applications(id) ON DELETE SET NULL,
 donor_name varchar(100) NOT NULL, channel_url text NOT NULL DEFAULT '',
 description_es varchar(600) NOT NULL, description_en varchar(600) NOT NULL,
 kind varchar(20) NOT NULL CHECK(kind IN ('money','giftcard','item')),
 currency varchar(3) NOT NULL DEFAULT '', gross_amount numeric(18,2),
 received_amount numeric(18,2), prize_amount numeric(18,2),
 custodian varchar(150) NOT NULL DEFAULT '', delivered_by varchar(150) NOT NULL DEFAULT '',
 evidence varchar(1500) NOT NULL DEFAULT '', public_identity boolean NOT NULL DEFAULT false,
 consent_evidence varchar(1000) NOT NULL DEFAULT '',
 status varchar(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','confirmed','reversed')),
 confirmed_at timestamptz, confirmed_by bigint REFERENCES users(id) ON DELETE SET NULL,
 revision bigint NOT NULL DEFAULT 1, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK((kind='item' AND currency='') OR (kind IN ('money','giftcard') AND currency ~ '^[A-Z]{3}$')),
 CHECK(received_amount IS NULL OR received_amount > 0),
 CHECK(prize_amount IS NULL OR (prize_amount > 0 AND received_amount IS NOT NULL AND prize_amount <= received_amount)),
 CHECK(kind<>'item' OR ((received_amount IS NULL OR received_amount=trunc(received_amount)) AND (prize_amount IS NULL OR prize_amount=trunc(prize_amount)))),
 CHECK(NOT public_identity OR consent_evidence<>''),
 CHECK(status<>'confirmed' OR (received_amount IS NOT NULL AND prize_amount IS NOT NULL AND custodian<>'' AND delivered_by<>'' AND evidence<>'' AND confirmed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_call_contribution_status ON tournament_call_contributions(status,id);
ALTER TABLE tournament_call_contributions ADD COLUMN IF NOT EXISTS payment_reference varchar(300) NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_call_payment_reference ON tournament_call_contributions(payment_reference) WHERE payment_reference<>'';
CREATE TABLE IF NOT EXISTS tournament_call_contribution_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contribution_id bigint NOT NULL REFERENCES tournament_call_contributions(id) ON DELETE RESTRICT,
 actor_id bigint REFERENCES users(id) ON DELETE SET NULL,
 action varchar(40) NOT NULL, snapshot jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_call_contribution_events ON tournament_call_contribution_events(contribution_id,id);
CREATE TABLE IF NOT EXISTS tournament_call_donation_intents (
 id uuid PRIMARY KEY, receipt_hash varchar(64) NOT NULL UNIQUE, reference varchar(150) NOT NULL UNIQUE,
 amount_usd numeric(18,2) NOT NULL CHECK(amount_usd>=1 AND amount_usd<=10000),
 amount_pen numeric(18,2) NOT NULL CHECK(amount_pen>0),
 public_identity boolean NOT NULL DEFAULT false, display_name varchar(100) NOT NULL DEFAULT '', consented_at timestamptz,
 token_hash varchar(64) NOT NULL DEFAULT '', device_hash varchar(64) NOT NULL DEFAULT '', payment_key_hash varchar(64) NOT NULL DEFAULT '',
 state varchar(30) NOT NULL DEFAULT 'prepared' CHECK(state IN ('prepared','processing','authenticating','charged','uncertain','failed')),
 charge_id varchar(255) NOT NULL DEFAULT '', is_test boolean NOT NULL DEFAULT false,
 contribution_id bigint UNIQUE REFERENCES tournament_call_contributions(id) ON DELETE RESTRICT,
 revision bigint NOT NULL DEFAULT 1, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(NOT public_identity OR (display_name<>'' AND consented_at IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_call_donation_charge ON tournament_call_donation_intents(charge_id) WHERE charge_id<>'';
ALTER TABLE tournament_call_donation_intents ADD COLUMN IF NOT EXISTS payment_key_hash varchar(64) NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS ix_call_donation_recovery ON tournament_call_donation_intents(state,created_at);
GRANT SELECT,INSERT,UPDATE ON tournament_call_contributions,tournament_call_donation_intents TO decatron_user;
GRANT SELECT,INSERT ON tournament_call_contribution_events TO decatron_user;
-- Existing default privileges may grant ALL on newly created tables. Keep the ledger and audit append-preserving.
REVOKE DELETE,TRUNCATE ON tournament_call_contributions,tournament_call_donation_intents FROM decatron_user;
REVOKE UPDATE,DELETE,TRUNCATE ON tournament_call_contribution_events FROM decatron_user;
GRANT USAGE,SELECT ON SEQUENCE tournament_call_contributions_id_seq,tournament_call_contribution_events_id_seq TO decatron_user;
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='decatron_app') THEN
  GRANT SELECT,INSERT,UPDATE ON tournament_call_contributions,tournament_call_donation_intents TO decatron_app;
  GRANT SELECT,INSERT ON tournament_call_contribution_events TO decatron_app;
  REVOKE DELETE,TRUNCATE ON tournament_call_contributions,tournament_call_donation_intents FROM decatron_app;
  REVOKE UPDATE,DELETE,TRUNCATE ON tournament_call_contribution_events FROM decatron_app;
  GRANT USAGE,SELECT ON SEQUENCE tournament_call_contributions_id_seq,tournament_call_contribution_events_id_seq TO decatron_app;
 END IF;
END $$;
COMMIT;
