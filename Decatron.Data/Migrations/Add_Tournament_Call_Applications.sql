BEGIN;
ALTER TABLE tournament_call_page ADD COLUMN IF NOT EXISTS applications_open boolean NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS tournament_call_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_key varchar(80) NOT NULL,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    channel_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind varchar(20) NOT NULL CHECK (kind IN ('participant','collaborator')),
    display_name text NOT NULL,
    channel_url text NOT NULL,
    avatar_url text NOT NULL DEFAULT '',
    contact varchar(254) NOT NULL,
    notes varchar(1500) NOT NULL DEFAULT '',
    contribution_type varchar(20) NOT NULL DEFAULT '',
    amount numeric(18,2),
    currency varchar(3) NOT NULL DEFAULT '',
    public_listing boolean NOT NULL DEFAULT false,
    uses_bot boolean NOT NULL DEFAULT false,
    will_stream boolean NOT NULL DEFAULT false,
    accepted_at timestamptz NOT NULL,
    rules_snapshot jsonb NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','withdrawn')),
    review_note varchar(1000) NOT NULL DEFAULT '',
    reviewed_at timestamptz,
    reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
    revision bigint NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_call_application_identity UNIQUE (identity_key, kind),
    CONSTRAINT ck_call_application_contribution CHECK (kind = 'participant' OR
        (contribution_type IN ('money','giftcard','vbucks') AND amount > 0 AND
         ((contribution_type = 'vbucks' AND amount = trunc(amount) AND currency = '') OR
          (contribution_type IN ('money','giftcard') AND currency ~ '^[A-Z]{3}$'))))
);
-- Do not let this feature block existing account/channel removal flows.
ALTER TABLE tournament_call_applications DROP CONSTRAINT IF EXISTS tournament_call_applications_user_id_fkey;
ALTER TABLE tournament_call_applications ADD CONSTRAINT tournament_call_applications_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE tournament_call_applications DROP CONSTRAINT IF EXISTS tournament_call_applications_channel_user_id_fkey;
ALTER TABLE tournament_call_applications ADD CONSTRAINT tournament_call_applications_channel_user_id_fkey
    FOREIGN KEY (channel_user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE tournament_call_applications DROP CONSTRAINT IF EXISTS tournament_call_applications_reviewed_by_fkey;
ALTER TABLE tournament_call_applications ADD CONSTRAINT tournament_call_applications_reviewed_by_fkey
    FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS ix_call_applications_review ON tournament_call_applications(kind,status,created_at,id);
CREATE INDEX IF NOT EXISTS ix_call_applications_user ON tournament_call_applications(user_id);
GRANT SELECT, INSERT, UPDATE ON tournament_call_applications TO decatron_user;
GRANT USAGE, SELECT ON SEQUENCE tournament_call_applications_id_seq TO decatron_user;
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'decatron_app') THEN
        GRANT SELECT, INSERT, UPDATE ON tournament_call_applications TO decatron_app;
        GRANT USAGE, SELECT ON SEQUENCE tournament_call_applications_id_seq TO decatron_app;
    END IF;
END $$;
COMMIT;
