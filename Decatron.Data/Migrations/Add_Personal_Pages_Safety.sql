BEGIN;

ALTER TABLE personal_pages ADD COLUMN IF NOT EXISTS forced_adult boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS personal_page_domains (
    domain varchar(253) PRIMARY KEY,
    kind varchar(10) NOT NULL CHECK (kind IN ('adult','blocked')),
    note varchar(300) NOT NULL DEFAULT '',
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS personal_page_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id bigint NOT NULL REFERENCES personal_pages(id) ON DELETE CASCADE,
    reporter_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason varchar(20) NOT NULL CHECK (reason IN ('adult_unmarked','scam','impersonation','hate','copyright','other')),
    detail varchar(1000) NOT NULL DEFAULT '',
    link_id varchar(40) NOT NULL DEFAULT '',
    link_url varchar(500) NOT NULL DEFAULT '',
    status varchar(10) NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved','dismissed')),
    resolution varchar(20) NOT NULL DEFAULT '' CHECK (resolution IN ('','hidden','forced_adult','domain_blocked')),
    review_note varchar(1000) NOT NULL DEFAULT '',
    reviewed_by bigint REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_personal_page_reports_review ON personal_page_reports(status, created_at, id);
CREATE INDEX IF NOT EXISTS ix_personal_page_reports_reporter ON personal_page_reports(reporter_user_id, created_at);
-- Una sola denuncia abierta por persona y página
CREATE UNIQUE INDEX IF NOT EXISTS uq_personal_page_reports_open
    ON personal_page_reports(page_id, reporter_user_id) WHERE status = 'open';

GRANT SELECT, INSERT, UPDATE, DELETE ON personal_page_domains, personal_page_reports TO decatron_user;
GRANT USAGE, SELECT ON SEQUENCE personal_page_reports_id_seq TO decatron_user;
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'decatron_app') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON personal_page_domains, personal_page_reports TO decatron_app;
        GRANT USAGE, SELECT ON SEQUENCE personal_page_reports_id_seq TO decatron_app;
    END IF;
END $$;

COMMIT;
